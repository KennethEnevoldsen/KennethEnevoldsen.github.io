#!/usr/bin/env python3
"""Keep the non-highlighted publication lists on docs/publications.md up to date.

Pipeline (stdlib only):
  1. fetch   OpenAlex works for the ORCID below  -> data/publications/openalex.bib (cache)
  2. merge   openalex.bib with data/publications/local.bib (local always wins)
  3. insert  the rendered lists between the two marker comments in docs/publications.md

Only the text between the markers is ever touched; "Highlights" and the rest of
the page are left alone.

Control files (all in data/publications/):
  local.bib    hand-maintained entries. `status` decides where an entry goes:
                 published | preprint | software -> rendered in the matching section
                 in-review                       -> kept here but NOT rendered; change
                                                    status to `published` when it is out
                 hidden                          -> never rendered (drop, but keep a record)
  exclude.txt  one pattern per line (OpenAlex id, DOI, or title substring) to drop
               OpenAlex entries. Lines starting with # are comments.
  openalex.bib generated cache. Do not edit.

OpenAlex works that are preprints (arXiv, medRxiv, OSF, ...) are never inserted
automatically; they are listed in the report as candidates instead.

Usage:
  OPENALEX_API_KEY=... python scripts/update_publications.py            # fetch + update
  python scripts/update_publications.py --no-fetch                      # use cached openalex.bib
  python scripts/update_publications.py --check                         # exit 1 if page is stale
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import unicodedata
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "publications"
LOCAL_BIB = DATA / "local.bib"
CACHE_BIB = DATA / "openalex.bib"
EXCLUDE = DATA / "exclude.txt"
PAGE = ROOT / "docs" / "publications.md"

ORCID = "https://orcid.org/0000-0001-8733-0966"
OWN_SURNAME = "Enevoldsen"
MAX_AUTHORS = 8  # longer author lists are cut to MAX_AUTHORS-1 names + "& others"
START = "<!-- publications:start (generated by scripts/update_publications.py; edit data/publications/*.bib instead) -->"
END = "<!-- publications:end -->"

SECTIONS = [
    ("published", "Peer-reviewed and Accepted", "*Sorted by year, but otherwise in no particular order*"),
    ("preprint", "Preprints and Reports", None),
    ("software", "Non-peer-reviewed software", None),
]
PREPRINT_SOURCES = ("arxiv", "medrxiv", "biorxiv", "osf", "socarxiv", "ssrn", "research square", "preprint", "zenodo")
SKIP_TYPES = {"peer-review", "preprint", "dataset", "other", "paratext", "erratum", "retraction"}
PARTICLES = {"van", "von", "de", "der", "den", "di", "da", "la", "le", "del", "al", "el", "bin", "ten", "ter"}


# --------------------------------------------------------------------------- bibtex
def parse_bib(text: str) -> list[dict]:
    entries, i, n = [], 0, len(text)
    while True:
        i = text.find("@", i)
        if i < 0:
            return entries
        m = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,").match(text, i)
        if not m:
            i += 1
            continue
        entry, pos = {"_type": m.group(1), "_key": m.group(2)}, m.end()
        while True:
            m2 = re.compile(r"\s*(\w[\w-]*)\s*=\s*\{").match(text, pos)
            if not m2:
                break
            depth, j = 1, m2.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(text[j], 0)
                j += 1
            entry[m2.group(1).lower()] = text[m2.end():j - 1].strip()
            pos = j
            m3 = re.compile(r"\s*,").match(text, pos)
            pos = m3.end() if m3 else pos
        entries.append(entry)
        i = pos


def write_bib(entries: list[dict], header: str = "") -> str:
    out = [header] if header else []
    for e in entries:
        lines = [f"@{e.get('_type', 'article')}{{{e['_key']},"]
        for k, v in e.items():
            if not k.startswith("_") and v:
                lines.append(f"  {k} = {{{v}}},")
        lines.append("}")
        out.append("\n".join(lines))
    return "\n\n".join(out) + "\n"


# --------------------------------------------------------------------------- helpers
def norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s.lower())
    s = "".join(c for c in s if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def year_of(e: dict) -> int:
    m = re.search(r"\d{4}", e.get("year", ""))
    return int(m.group()) if m else 0


def norm_doi(d: str) -> str:
    return re.sub(r"^https?://(dx\.)?doi\.org/", "", d.strip().lower())


def entry_doi(e: dict) -> str:
    if e.get("doi"):
        return norm_doi(e["doi"])
    m = re.search(r"doi\.org/(\S+)", e.get("url", ""))
    return norm_doi(m.group(1)) if m else ""


def same_work(a: dict, b: dict) -> bool:
    if a.get("openalex") and a.get("openalex") == b.get("openalex"):
        return True
    da, db = entry_doi(a), entry_doi(b)
    if da and db and da == db:
        return True
    ta, tb = norm(a.get("title", "")), norm(b.get("title", ""))
    if len(ta) < 12 or len(tb) < 12:
        return ta == tb and bool(ta)
    if ta == tb or ta in tb or tb in ta:  # containment: a local title may include extra text
        return True
    wa, wb = set(ta.split()), set(tb.split())  # retitled versions of the same paper
    return len(wa & wb) / len(wa | wb) >= 0.6


def initials(given: str) -> str:
    parts = []
    for tok in re.split(r"\s+", given.strip()):
        if not tok:
            continue
        parts.append("-".join(p[0].upper() + "." for p in tok.split("-") if p))
    return " ".join(parts)


def to_bib_name(display: str) -> str:
    """'Kenneth C. Enevoldsen' -> 'Enevoldsen, K. C.'"""
    toks = display.replace("–", "-").split()
    if len(toks) < 2:
        return display
    i = len(toks) - 1
    while i > 1 and toks[i - 1].lower() in PARTICLES:
        i -= 1
    return f"{' '.join(toks[i:])}, {initials(' '.join(toks[:i]))}"


def render_authors(author_field: str, truncate: bool = False) -> str:
    names = [a.strip() for a in re.split(r"\s+and\s+", author_field) if a.strip()]

    def fmt(n: str) -> str:
        return f"**{n}**" if n.startswith(OWN_SURNAME + ",") else n

    if "…" in names:  # explicit truncation: "A, B, … Z"
        k = names.index("…")
        return ", ".join(fmt(n) for n in names[:k]) + ", … " + fmt(names[-1])
    others = names and names[-1] == "others"
    if others:
        names = names[:-1]
    elif truncate and len(names) > MAX_AUTHORS:
        names, others = names[: MAX_AUTHORS - 1], True
    names = [fmt(n) for n in names]
    if others:
        return ", ".join(names) + ", & others."
    if len(names) == 1:
        return names[0]
    return ", ".join(names[:-1]) + ", & " + names[-1]


def end_sentence(s: str) -> str:
    return s if s.endswith((".", "?", "!")) else s + "."


def render_entry(e: dict) -> str:
    year = e.get("year", "n.d.")
    line = f"- {render_authors(e.get('author', ''), truncate=bool(e.get('openalex')))} ({year}). {end_sentence(e['title'])}"
    venue = e.get("journal", "")
    if venue:
        if e.get("volume"):
            venue += f", {e['volume']}" + (f"({e['number']})" if e.get("number") else "")
        if e.get("pages"):
            venue += f", {e['pages']}"
        line += " " + end_sentence(venue)
    url = e.get("url") or (f"https://doi.org/{entry_doi(e)}" if entry_doi(e) else "")
    if url and url not in line:
        if not line.endswith("."):
            line += "."
        line += f" {url}"
    return line


# --------------------------------------------------------------------------- OpenAlex
def fetch_openalex(api_key: str) -> list[dict]:
    works, cursor = [], "*"
    select = "id,doi,title,publication_year,type,authorships,primary_location,biblio"
    while cursor:
        params = {
            "filter": f"authorships.author.orcid:{ORCID}",
            "per-page": 100,
            "cursor": cursor,
            "select": select,
        }
        if api_key:
            params["api_key"] = api_key
        url = "https://api.openalex.org/works?" + urllib.parse.urlencode(params)
        req = urllib.request.Request(url, headers={"User-Agent": "publications-updater"})
        with urllib.request.urlopen(req, timeout=60) as r:
            data = json.load(r)
        works += data["results"]
        cursor = data["meta"].get("next_cursor") if data["results"] else None
    return works


def work_to_entry(w: dict) -> dict:
    loc = w.get("primary_location") or {}
    source = (loc.get("source") or {}).get("display_name") or ""
    biblio = w.get("biblio") or {}
    pages = "–".join(p for p in (biblio.get("first_page"), biblio.get("last_page")) if p)
    if biblio.get("first_page") and biblio.get("first_page") == biblio.get("last_page"):
        pages = biblio["first_page"]
    authors = [to_bib_name(a["author"]["display_name"]) for a in w.get("authorships", [])]
    is_preprint = w.get("type") == "preprint" or any(s in source.lower() for s in PREPRINT_SOURCES)
    oa_id = w["id"].rsplit("/", 1)[-1]
    first = norm(authors[0].split(",")[0]).replace(" ", "") if authors else "anon"
    word = (norm(w.get("title") or "").split() or ["x"])[0]
    return {
        "_type": "article",
        "_key": f"{first}{w.get('publication_year', '')}{word}-{oa_id}",
        "author": " and ".join(authors),
        "year": str(w.get("publication_year") or ""),
        "title": re.sub(r"[{}]", "", (w.get("title") or "").strip()),
        "journal": source,
        "volume": biblio.get("volume") or "",
        "number": biblio.get("issue") or "",
        "pages": pages,
        "doi": norm_doi(w.get("doi") or ""),
        "url": loc.get("landing_page_url") if not w.get("doi") else "",
        "openalex": oa_id,
        "openalex_type": w.get("type") or "",
        "status": "preprint" if is_preprint else "published",
    }


# --------------------------------------------------------------------------- merge + render
def load_excludes() -> list[str]:
    if not EXCLUDE.exists():
        return []
    return [
        l.strip().lower()
        for l in EXCLUDE.read_text().splitlines()
        if l.strip() and not l.lstrip().startswith("#")
    ]


def is_excluded(e: dict, patterns: list[str]) -> bool:
    hay = [e.get("openalex", "").lower(), entry_doi(e), e.get("title", "").lower()]
    return any(p in h for p in patterns for h in hay if h)


def source_rank(e: dict):
    """Which OpenAlex record to keep when one work has several: published > arXiv > other preprint servers > no venue."""
    j = e.get("journal", "").lower()
    return (e["status"] != "published", "arxiv" not in j or "socarxiv" in j, j == "")


def merge(local: list[dict], cached: list[dict], excludes: list[str]):
    candidates, promotions, added = [], [], []
    seen = list(local)
    for oa in sorted(cached, key=source_rank):
        if oa.get("openalex_type") in SKIP_TYPES and oa["status"] != "preprint":
            continue
        if is_excluded(oa, excludes):
            continue
        match = next((l for l in seen if same_work(l, oa)), None)
        if match is not None:
            if match.get("status") in ("in-review", "preprint") and oa["status"] == "published":
                promotions.append((match, oa))
            continue
        seen.append(oa)
        (candidates if oa["status"] == "preprint" else added).append(oa)
    return added, candidates, promotions


def render_block(entries: list[dict]) -> str:
    out = []
    for status, heading, blurb in SECTIONS:
        group = [e for e in entries if e.get("status", "published") == status]
        if not group:
            continue
        group = sorted(group, key=lambda e: -year_of(e))  # stable: keeps file order within a year
        out.append(f"## {heading}\n")
        if blurb:
            out.append(blurb + "\n")
        out.append("\n".join(render_entry(e) for e in group) + "\n")
    return "\n".join(out)


def insert(page: str, block: str) -> str:
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(page):
        sys.exit(f"markers not found in {PAGE}; add\n{START}\n{END}")
    return pat.sub(lambda _: f"{START}\n\n{block}\n{END}", page, count=1)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-fetch", action="store_true", help="use cached openalex.bib")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the page would change")
    ap.add_argument("--report", type=Path, help="write a markdown report (for the PR body)")
    args = ap.parse_args()

    if not args.no_fetch:
        key = os.environ.get("OPENALEX_API_KEY", "")
        try:
            works = fetch_openalex(key)
            entries = sorted((work_to_entry(w) for w in works), key=lambda e: e["openalex"])
            CACHE_BIB.write_text(write_bib(entries, "% Generated by scripts/update_publications.py from OpenAlex. Do not edit.\n"))
            print(f"fetched {len(entries)} works from OpenAlex")
        except Exception as exc:  # network/API trouble must not wipe the page
            print(f"warning: OpenAlex fetch failed ({exc}); using cache", file=sys.stderr)

    local = parse_bib(LOCAL_BIB.read_text())
    cached = parse_bib(CACHE_BIB.read_text()) if CACHE_BIB.exists() else []
    added, candidates, promotions = merge(local, cached, load_excludes())

    merged = [e for e in local if e.get("status", "published") != "hidden"] + added
    page = PAGE.read_text()
    new = insert(page, render_block(merged))

    lines = []
    if added:
        lines += ["### New from OpenAlex (inserted)", *[f"{render_entry(e)}  \n  `{e['openalex']}`" for e in added], ""]
    if promotions:
        lines += ["### Preprint / in-review entries that now look published", "Set `status = {published}` in `local.bib` to show them:",
                  *[f"- `{l['_key']}` ≈ {o.get('journal') or 'n/a'} ({o['year']})" for l, o in promotions], ""]
    if candidates:
        lines += ["### Preprints found on OpenAlex (not inserted)", "Add to `local.bib` (`status = {preprint}` or `{in-review}`) or to `exclude.txt`:",
                  *[f"- {e['year']} {e['title']} — `{e['openalex']}`" for e in candidates], ""]
    report = "\n".join(lines) or "No changes in OpenAlex results."
    print(report)
    if args.report:
        args.report.write_text(report + "\n")
    if summary := os.environ.get("GITHUB_STEP_SUMMARY"):
        Path(summary).open("a").write(report + "\n")

    if new != page:
        if args.check:
            print("docs/publications.md is out of date", file=sys.stderr)
            return 1
        PAGE.write_text(new)
        print("updated docs/publications.md")
    else:
        print("docs/publications.md already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
